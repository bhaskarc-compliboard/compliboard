// Checks the places where code names a database object as a STRING, which TypeScript
// cannot verify. Runs as part of `npm run check`.
//
//   node scripts/check-schema-contracts.js
//
// WHY THIS EXISTS
//
// On 11 September migration 007 renamed `requirement_templates.industry` to
// `industries text[]`. `/api/industries` — named in 007's own header as the only caller —
// kept selecting the old name. PostgREST answered `42703: column does not exist`, the
// route turned that into a 500, and the signup dropdown came back empty. Signup was
// blocked in production and nothing said so.
//
// `npm run check` passed the entire time. A column name inside `.select('industry')` is a
// string literal. The generated types cannot see into it, which is precisely what makes
// them valuable everywhere else — a wrong column in typed code is a compile error, and a
// wrong column in a query string is a runtime 500 on a page nobody was watching.
//
// It reads lib/database.types.ts rather than the live database, so it needs no network
// and no credentials and gives the same answer every time. That file is regenerated by
// `npm run db:types` after every migration, so it IS the schema as the code understands
// it — and if it is stale, that is itself worth failing on.
//
// ---------------------------------------------------------------------------
// *** KNOWN BLIND SPOT: A VARIABLE TABLE NAME CANNOT BE ATTRIBUTED. ***
//
// Check 1 associates each `.from('literal')` with the query chained off it. Where the
// table is a variable — `db.from(table)` — there is no literal to attribute, and this
// script skips it. Neither can the compiler.
//
// There are TWO such call sites today, and BOTH MUST BE CHECKED BY HAND after any rename:
//
//   app/api/account/export/route.ts   byCompany(table)  — loops tables, filters company_id
//   app/api/account/route.ts          DELETE            — loops a table list, same filter
//
// Check 2 below covers the second of those specifically, because it is the deletion path
// and the cost of it being wrong is a customer's data surviving a deletion they asked for.
// The export one is covered only by the fact that both use the same `company_id` filter,
// so check 2 failing implies the export is suspect too.
// ---------------------------------------------------------------------------

import { readFileSync, readdirSync, statSync } from "fs";
import { join, dirname, relative } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TYPES = join(ROOT, "lib/database.types.ts");

// ---------------------------------------------------------------------------
// Parse the generated types into { table: Set<column> }.
// ---------------------------------------------------------------------------
// *** VIEWS ARE READ TOO, AND THEY WERE NOT UNTIL 13 SEP 2026. ***
//
// The generated types put views under `Views:`, and this parser only ever walked `Tables:`.
// So every `.from(<a view>)` was reported as "no such table" — a FALSE POSITIVE that looks
// exactly like the true positive this script exists to produce, which is the worse of the two
// failures: a checker that cries wolf gets its output skimmed, and the next real finding is
// skimmed with it (HOW-WE-BUILD §4 on the abort guard).
//
// Found when the first view in the project — `obligation_evidence_state`, migration 020 — was
// queried from a route. The script was right that the embed was illegal (PostgREST cannot
// embed a view with no FK) and wrong about the plain `.from()` that replaced it. One run, one
// true finding and one false one, indistinguishable in the output.
function loadSchema() {
  const src = readFileSync(TYPES, "utf8");
  const tablesAt = src.indexOf("Tables: {");
  if (tablesAt === -1) fail("lib/database.types.ts has no `Tables:` block. Run `npm run db:types`.");

  const schema = {};
  const views = new Set();
  for (const blockName of ["Tables: {", "Views: {"]) {
    const at = src.indexOf(blockName);
    if (at === -1) continue;
    const before = new Set(Object.keys(schema));
    collectBlock(src, at, schema);
    if (blockName.startsWith("Views")) {
      for (const k of Object.keys(schema)) if (!before.has(k)) views.add(k);
    }
  }
  // *** A VIEW HAS NO ROWS OF ITS OWN, SO IT CANNOT BE DELETED FROM. *** The deletion sweep
  // below asks whether every relation carrying company_id is named in /api/account's DELETE.
  // For a view that question is meaningless: deleting its base tables removes what it shows.
  // Without this the first view in the project produced a finding that could only be silenced
  // by adding a lie to the deletion list.
  schema.__views__ = views;
  const n = Object.keys(schema).length;
  if (n < 5) fail(`Parsed only ${n} relations from lib/database.types.ts — the parser and the file disagree.`);
  return schema;
}

function collectBlock(src, blockAt, schema) {
  // Walk the block, brace-counting, collecting `name: { Row: { ...keys } }`.
  let i = src.indexOf("{", blockAt) + 1, table = null, inRow = false, rowDepth = 0;
  const lines = src.slice(i).split("\n");
  let d = 1;
  for (const line of lines) {
    const t = line.trim();
    if (d === 1) {
      const m = t.match(/^([a-z_0-9]+): \{$/);
      if (m) { table = m[1]; schema[table] = new Set(); }
    }
    if (d === 2 && table && /^Row: \{$/.test(t)) { inRow = true; rowDepth = d; }
    else if (inRow && d === rowDepth + 1) {
      const m = t.match(/^([a-z_0-9]+)(\??):/);
      if (m) schema[table].add(m[1]);
    }
    for (const ch of line) { if (ch === "{") d++; else if (ch === "}") d--; }
    if (inRow && d <= rowDepth) inRow = false;
    if (d <= 0) break;
  }
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (["node_modules", ".next", ".git", "supabase"].includes(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    // Skips itself: this file documents the patterns it looks for, so scanning it finds
    // its own examples.
    else if (/\.(ts|tsx|js|mjs)$/.test(name)
             && !p.includes("database.types")
             && !p.endsWith("check-schema-contracts.js")) out.push(p);
  }
  return out;
}

const problems = [];
let paidGatedCount = 0, paidTotalCount = 0;
const note = (file, msg) => problems.push(`${relative(ROOT, file)}\n      ${msg}`);
function fail(msg) { console.error(`\n  check-schema-contracts: ${msg}\n`); process.exit(1); }

const schema = loadSchema();
/**
 * Every foreign-key name the generated types know, read ONCE — a disambiguated embed
 * (`related!constraint(cols)`) names one of these, and a name that is not here is a real error.
 * Module level and not per file: there are ~280 files and one types file.
 */
const FK_NAMES = new Set([...readFileSync(TYPES, "utf8")
  .matchAll(/foreignKeyName: "([a-z_0-9]+)"/g)].map((m) => m[1]));
const files = walk(ROOT);

// ---------------------------------------------------------------------------
// CHECK 1 — every column named in a query string exists on the table queried.
// ---------------------------------------------------------------------------
const FROM = /\.from\(\s*['"]([a-z_0-9]+)['"]\s*\)/g;
const COLMETH = /\.(eq|neq|gt|gte|lt|lte|like|ilike|is|in|contains|containedBy|overlaps|order)\(\s*['"]([a-z_0-9]+)['"]/g;
const SELECT = /\.select\(\s*[`'"]([\s\S]*?)[`'"]\s*[,)]/;

let skippedDynamic = 0;
const dynamicSites = [];
for (const file of files) {
  const src = readFileSync(file, "utf8");
  // Only genuine PostgREST calls: preceded by a supabase client, and excluding
  // Array.from(...) and storage.from(BUCKET). An inflated count would misstate the size
  // of the blind spot, and the point of reporting it is that it is honestly small.
  for (const m of src.matchAll(/(\w+)\.from\(\s*([a-zA-Z_$][\w$]*)\s*\)/g)) {
    if (!/^(supabase|supabaseAdmin|db|client)$/.test(m[1])) continue;   // not Array.from, not Buffer.from, not storage.from
    skippedDynamic++;
    dynamicSites.push(`${relative(ROOT, file)}: ${m[1]}.from(${m[2]})`);
  }

  // Boundaries are EVERY `.from(` — literal or variable. Ending a window only at the next
  // LITERAL one attributes a dynamic query's filters to whichever literal table came
  // before it, which is precisely the false positive this script exists to avoid emitting.
  const anyFrom = [...src.matchAll(/\.from\(/g)].map((m) => m.index);
  const cuts = [...src.matchAll(FROM)];
  for (let k = 0; k < cuts.length; k++) {
    const table = cuts[k][1];
    const start = cuts[k].index + cuts[k][0].length;
    const nextFrom = anyFrom.find((i) => i > cuts[k].index);
    const end = Math.min(nextFrom ?? src.length, start + 1200);
    const body = src.slice(start, end);

    if (!schema[table]) { note(file, `.from('${table}') — no such table in the generated schema`); continue; }
    const cols = schema[table];

    const sel = body.match(SELECT);
    if (sel) {
      const raw = sel[1];
      // *** AN EMBED MAY NAME ITS FOREIGN KEY, AND THAT IS NOT A COLUMN — 15 October 2026. ***
      //
      // PostgREST's disambiguating form is `related_table!constraint_name(cols)`, and it is not
      // optional: where TWO foreign keys join the same pair of tables, a bare `related_table(cols)`
      // is refused with `PGRST201: Could not embed because more than one relationship was found`.
      // Calendar step 6 created exactly that pair — `document_deadlines.calendar_event_id` →
      // `calendar_events.id` (migration 040) and `calendar_events.deadline_id` →
      // `document_deadlines.id` (073) — so `app/api/documents/report/route.ts` has to name the key.
      //
      // This script read `calendar_events!document_deadlines_calendar_event_id_fkey` as two
      // identifiers and reported BOTH as unknown, on a query proven to work against staging. Two
      // false positives on a correct line is the failure `HOW-WE-BUILD.md` §4 is about: a guard that
      // cries wolf gets its output skimmed, and the next real finding is skimmed with it.
      //
      // So the constraint name is stripped before anything is judged, and it IS judged — against
      // the generated types' own `foreignKeyName` values, so a key that does not exist is still
      // caught. `lib/database.types.ts` carries every one.
      for (const [, rel, fk] of raw.matchAll(/([a-z_0-9]+)!([a-z_0-9]+)\s*\(/g)) {
        if (!schema[rel]) note(file, `.from('${table}').select(...) embeds '${rel}', which is not a table`);
        if (!FK_NAMES.has(fk)) note(file, `.from('${table}').select(...) embeds through '${fk}', which is not a foreign key in the generated types`);
      }
      // ...and now the plain form, with any `!constraint` already accounted for above.
      const bare = raw.replace(/([a-z_0-9]+)!([a-z_0-9]+)(\s*\()/g, "$1$3");
      // A nested `other_table ( cols )` is an embedded resource, checked as its own table.
      for (const [, rel] of bare.matchAll(/([a-z_0-9]+)\s*\(/g)) {
        if (!schema[rel] && !cols.has(rel)) note(file, `.from('${table}').select(...) embeds '${rel}', which is neither a table nor a column`);
      }
      const flat = bare.replace(/[a-z_0-9]+\s*\([^)]*\)/g, " ");
      for (const name of flat.match(/[a-z_0-9]+/g) || []) {
        if (["count", "exact", "head", "planned", "estimated"].includes(name)) continue;
        if (!cols.has(name)) note(file, `.from('${table}').select('… ${name} …') — no such column`);
      }
    }
    for (const [, method, name] of body.matchAll(COLMETH)) {
      if (!cols.has(name)) note(file, `.from('${table}').${method}('${name}', …) — no such column`);
    }
  }
}

// ---------------------------------------------------------------------------
// CHECK 2 — the account-deletion path names every company-scoped table.
//
// /api/account DELETE destroys a company. It enumerates the tables to clear as a list of
// strings. A list is a snapshot of a set that grows: the next table created with a
// company_id and no cascade is a row that SURVIVES a deletion the customer asked for, in
// the one route where that is unambiguously a breach.
//
// So every table carrying company_id must be either in that list or in the exemption list
// beside it, which carries a reason per table. Adding a table now forces that decision at
// build time instead of leaving it to be discovered.
// ---------------------------------------------------------------------------
const ACCOUNT = join(ROOT, "app/api/account/route.ts");
const accountSrc = readFileSync(ACCOUNT, "utf8");
const listOf = (name) => {
  const m = accountSrc.match(new RegExp(`${name}\\s*=\\s*\\[([\\s\\S]*?)\\]`));
  return m ? [...m[1].matchAll(/'([a-z_0-9]+)'/g)].map((x) => x[1]) : null;
};
const deleted = listOf("COMPANY_SCOPED_TABLES");
const exempt = listOf("DELETED_BY_CASCADE_OR_PARENT");

if (!deleted || !exempt) {
  note(ACCOUNT, "expected COMPANY_SCOPED_TABLES and DELETED_BY_CASCADE_OR_PARENT arrays — check 2 cannot run");
} else {
  const withCompanyId = Object.entries(schema)
    .filter(([, cols]) => cols.has("company_id"))
    .map(([t]) => t)
    .sort();
  const named = new Set([...deleted, ...exempt]);
  const views = schema.__views__ ?? new Set();
  for (const t of withCompanyId) {
    if (views.has(t)) continue;   // a view has no rows to delete — see loadSchema()
    if (!named.has(t)) {
      note(ACCOUNT,
        `'${t}' carries company_id and is named in NEITHER list.\n` +
        `      A company deletion would leave its rows behind. Add it to COMPANY_SCOPED_TABLES,\n` +
        `      or to DELETED_BY_CASCADE_OR_PARENT with the reason it does not need naming.`);
    }
  }
  for (const t of named) {
    if (!schema[t]) note(ACCOUNT, `'${t}' is listed for deletion but is not a table in the generated schema`);
    else if (!schema[t].has("company_id")) note(ACCOUNT, `'${t}' is listed for deletion but has no company_id column`);
  }
}

// ---------------------------------------------------------------------------
// CHECK 3 — every route that can reach a model applies the read-only rule.
//
// `ACCOUNT-PLAN.md` decision 11: after the trial, or after a failed card's grace, a company
// may read and download everything and spend nothing. That is enforced by `requireAccess`
// in each paid route and by `splitByAccess` in each sweep.
//
// *** A LIST OF ROUTES IS A SNAPSHOT OF A SET THAT GROWS, WHICH IS CHECK 2'S WHOLE LESSON. ***
// And the set was already wrong once: step 17 assembled it by grepping for `@/lib/ai`, which
// finds only DIRECT importers, and reported 14 person-triggered paid routes. The real number
// is 19. The five it missed — `handbooks` POST, `handbooks/read` POST, `document-rescan`,
// `document-batches` PATCH action='start' and the audit section `retry` — all spend by
// calling a sweep in `after()`, so no amount of reading their own source would have found
// them. Only the transitive closure does.
//
// So this computes the closure rather than trusting a list: a route is PAID if it, or
// anything it imports transitively, imports the Anthropic SDK or posts to api.anthropic.com.
// Every paid route must call `requireAccess`, or be named in EXEMPT below WITH A REASON.
//
// Nineteen is also asserted as a COUNT. A twentieth paid route is then a deliberate edit here
// — which is exactly what nobody made when the five above were added.
// ---------------------------------------------------------------------------
const PAID_COUNT = 19;

// Why each of these may reach a model and still not call `requireAccess`.
const EXEMPT = {
  "app/api/topics/[id]/route.ts":
    "GET and DELETE only. The closure reaches lib/ai.ts through a module it imports for types " +
    "and helpers, but neither handler spends — reading and deleting a conversation are free.",
  "app/api/jobs/summarise/route.ts":
    "A cron. The rule is applied per company inside the sweep by splitByAccess, not per request.",
  "app/api/jobs/scan-documents/route.ts":
    "A cron — splitByAccess inside the sweep.",
  "app/api/jobs/audit-sections/route.ts":
    "A cron — splitByAccess inside the sweep.",
  "app/api/jobs/handbook-checks/route.ts":
    "A cron — splitByAccess inside lib/handbookCheck.ts sweepChecks.",
  "app/api/jobs/handbook-queue/route.ts":
    "A cron, and it spends NOTHING: queueDueChecks inserts rows and calls no model. Its paid " +
    "work is sweepChecks, kicked in after(), and that is gated. Queueing for a read-only " +
    "company is correct — decision 11 leaves work queued, it does not refuse to record it.",
};

{
  const rel = (f) => relative(ROOT, f);
  const srcOf = new Map(files.map((f) => [rel(f), readFileSync(f, "utf8")]));
  const resolveSpec = (from, spec) => {
    let base;
    if (spec.startsWith("@/")) base = join(ROOT, spec.slice(2));
    else if (spec.startsWith(".")) base = join(dirname(join(ROOT, from)), spec);
    else return null;
    for (const c of [base, base + ".ts", base + ".tsx", join(base, "index.ts"), join(base, "index.tsx")]) {
      const r = relative(ROOT, c);
      if (srcOf.has(r)) return r;
    }
    return null;
  };
  const spendsDirectly = (f) => /@anthropic-ai|api\.anthropic\.com/.test(srcOf.get(f) ?? "");
  const memo = new Map();
  const reaches = (f, stack = new Set()) => {
    if (memo.has(f)) return memo.get(f);
    if (stack.has(f)) return false;
    stack.add(f);
    let r = spendsDirectly(f);
    if (!r) {
      for (const m of (srcOf.get(f) ?? "").matchAll(/(?:from|import)\s*\(?\s*['"]([^'"]+)['"]/g)) {
        const d = resolveSpec(f, m[1]);
        if (d && reaches(d, stack)) { r = true; break; }
      }
    }
    stack.delete(f);
    memo.set(f, r);
    return r;
  };

  const routes = [...srcOf.keys()].filter((f) => /^app\/api\/.*\/route\.ts$/.test(f)).sort();
  const paid = routes.filter((f) => reaches(f));
  const gated = paid.filter((f) => /requireAccess\(/.test(srcOf.get(f) ?? ""));
  const ungated = paid.filter((f) => !/requireAccess\(/.test(srcOf.get(f) ?? ""));

  for (const f of ungated) {
    if (!EXEMPT[f]) {
      note(join(ROOT, f),
        "can reach a model but never calls requireAccess.\n" +
        "      A read-only company would spend here (ACCOUNT-PLAN decision 11). Add the two lines\n" +
        "      beside requireCompany, or name it in EXEMPT in this script with the reason.");
    }
  }
  for (const f of Object.keys(EXEMPT)) {
    if (!srcOf.has(f)) note(join(ROOT, "scripts/check-schema-contracts.js"),
      `EXEMPT names '${f}', which is not a route file. A stale exemption is a hole.`);
    else if (!paid.includes(f)) note(join(ROOT, "scripts/check-schema-contracts.js"),
      `EXEMPT names '${f}', which can no longer reach a model. Remove it — an exemption that\n` +
      "      is not needed hides the day it becomes needed again.");
  }
  if (gated.length !== PAID_COUNT) {
    note(join(ROOT, "scripts/check-schema-contracts.js"),
      `${gated.length} routes call requireAccess; PAID_COUNT says ${PAID_COUNT}.\n` +
      "      If a paid route was added or removed, change PAID_COUNT deliberately and say why.");
  }
  paidGatedCount = gated.length;
  paidTotalCount = paid.length;
}

// ---------------------------------------------------------------------------
if (problems.length) {
  console.error(`\n  check-schema-contracts: ${problems.length} problem(s).\n`);
  for (const p of problems) console.error(`    ${p}`);
  console.error(
    "\n  These are database identifiers written as strings, so neither tsc nor the\n" +
    "  generated types can catch them. If a migration just renamed or dropped a column,\n" +
    "  this is the sweep that was owed. If lib/database.types.ts is stale, run\n" +
    "  `npm run db:types` first.\n");
  process.exit(1);
}

// *** COUNT THE RELATIONS, NOT THE KEYS. *** `schema` carries a `__views__` sentinel alongside
// the real relations, so `Object.keys(schema).length` reported 28 when the database holds 26
// tables and 1 view. A headline number that is one too high is worse than no number: it was
// quoted into commit messages and docs all of 13 Sep before anyone subtracted it from a
// catalog query. Say what each half is, so the next person can check it without reading this.
const viewCount = schema.__views__.size;
const tableCount = Object.keys(schema).length - 1 - viewCount;

console.log(
  `  check-schema-contracts: ok — ${files.length} files, ` +
  `${tableCount + viewCount} relations (${tableCount} tables + ${viewCount} view${viewCount === 1 ? "" : "s"}).\n` +
  `    ${skippedDynamic} dynamic .from(variable) call site(s), which cannot be checked here:\n` +
  dynamicSites.map((s) => `      ${s}`).join("\n") +
  `\n    Check these by hand after any column rename — see the blind-spot note above.\n` +
  `    ${paidTotalCount} route(s) can reach a model; ${paidGatedCount} call requireAccess, ` +
  `${paidTotalCount - paidGatedCount} exempt with a reason (check 3).`);
